package addons

import (
	"bytes"
	"encoding/json"
	"fmt"
)

// GenerateTS는 등록된 애드온의 manifest를 프론트 목록(frontend/src/addons/manifests.gen.ts)으로 만든다.
// 프론트는 이 목록의 키로 컴파일 타임 애드온 id 타입(AddonId)을 얻고, title·icon은
// AddonManifest 타입으로 번역 키·아이콘 이름인지 tsc가 검사한다.
func (r *Registry) GenerateTS() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(`// Code generated by cmd/genaddons. DO NOT EDIT.
// 원본: backend/internal/addons/builtin
// ` + "`make types`" + `로 다시 생성한다.

import type { AddonManifest } from './types'

export const MANIFESTS = {
`)
	for _, a := range r.addons {
		m, err := json.MarshalIndent(a.Manifest, "  ", "  ")
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "  %q: %s,\n", a.Manifest.ID, m)
	}
	b.WriteString(`} as const satisfies Record<string, AddonManifest>

export type AddonId = keyof typeof MANIFESTS
`)
	return b.Bytes(), nil
}
