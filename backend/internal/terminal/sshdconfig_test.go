package terminal

import (
	"slices"
	"strings"
	"testing"
)

func TestParseSSHDConfig(t *testing.T) {
	// OMV가 만드는 형식을 본뜬 합성 설정. 추가 옵션의 Match 블록 안 값은 읽지 않는다.
	in := `# This file is auto-generated by openmediavault
Protocol 2
port 2222
Port 2200
AllowGroups root _ssh
allowgroups=staff
PasswordAuthentication no
Match Address 127.0.0.1,::1
    Port 22
    AllowGroups other
Match all
Include /etc/ssh/sshd_config.d/*.conf
`
	c, err := ParseSSHDConfig(strings.NewReader(in))
	if err != nil {
		t.Fatal(err)
	}
	if c.Port != 2222 {
		t.Errorf("port = %d, want 2222", c.Port)
	}
	if want := []string{"root", "_ssh", "staff"}; !slices.Equal(c.AllowGroups, want) {
		t.Errorf("allow groups = %q, want %q", c.AllowGroups, want)
	}

	c, _ = ParseSSHDConfig(strings.NewReader("Port abc\nPort 70000\n"))
	if c.Port != 0 || c.AllowGroups != nil {
		t.Errorf("invalid config = %+v", c)
	}
}

func TestCheckAddr(t *testing.T) {
	for _, ok := range []string{"", "auto", "127.0.0.1:22", "[::1]:2222", "127.0.0.2:22"} {
		if err := CheckAddr(ok); err != nil {
			t.Errorf("%q: %v", ok, err)
		}
	}
	for _, bad := range []string{"192.168.0.10:22", "localhost:22", "127.0.0.1", "127.0.0.1:0", ":22", "[::]:22"} {
		if CheckAddr(bad) == nil {
			t.Errorf("%q accepted", bad)
		}
	}
}
